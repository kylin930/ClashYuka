core::Result<void> ValidateRuntimeConfigDefinition(const RuntimeConfigDefinition& definition) {
    if (definition.host.empty()) {
        return MakeError(ErrorKind::InvalidConfig, "the controller host must not be empty");
    }
    if (definition.host == "0.0.0.0" || definition.host == "::" || definition.host == "*") {
        return MakeError(ErrorKind::InvalidConfig,
                         "the controller host must not be a wildcard address");
    }
    if (!IsValidPort(definition.port)) {
        return MakeError(ErrorKind::InvalidConfig, "the controller port is out of range");
    }
    if (!IsValidPort(definition.mixedPort)) {
        return MakeError(ErrorKind::InvalidConfig, "the mixed port is out of range");
    }
    if (definition.mixedPort == definition.port) {
        return MakeError(ErrorKind::InvalidConfig,
                         "the mixed port and controller port must differ");
    }
    if (definition.mode != "rule" && definition.mode != "global" && definition.mode != "direct") {
        return MakeError(ErrorKind::InvalidConfig, "unsupported proxy mode");
    }
    if (definition.logLevel != "info" && definition.logLevel != "warning" &&
        definition.logLevel != "error" && definition.logLevel != "debug") {
        return MakeError(ErrorKind::InvalidConfig, "unsupported log level");
    }
    return {};
}

std::string RenderRuntimeConfig(const RuntimeConfigDefinition& definition) {
    YAML::Node root;
    root["mixed-port"] = definition.mixedPort;
    root["allow-lan"] = false;
    root["bind-address"] = "127.0.0.1";
    root["mode"] = definition.mode;
    root["log-level"] = definition.logLevel;
    root["external-controller"] =
        definition.host + ":" + std::to_string(definition.port);
    root["secret"] = definition.secret;

    YAML::Emitter emitter;
    emitter << root;

    std::ostringstream output;
    output << kMarker << "\n\n" << emitter.c_str() << "\n";
    return output.str();
}

core::Result<RuntimeConfigInfo> EnsureRuntimeConfig(const std::string& path,
                                                    const RuntimeConfigDefinition& definition) {
    const core::Result<void> valid = ValidateRuntimeConfigDefinition(definition);
    if (!valid) {
        return valid.error();
    }

    const fs::path file = PathFromUtf8(path);
    std::error_code existsError;
    const bool exists = fs::exists(file, existsError);
    if (existsError) {
        return MakeError(ErrorKind::ConfigFailed,
                         "could not inspect the runtime config: " + existsError.message());
    }

    const std::string rendered = RenderRuntimeConfig(definition);

    if (!exists) {
        const core::Result<void> written = WriteConfigFile(path, rendered);
        if (!written) {
            return written.error();
        }
        RuntimeConfigInfo info;
        info.host = definition.host;
        info.port = definition.port;
        info.mixedPort = definition.mixedPort;
        info.secret = definition.secret;
        info.generated = true;
        return info;
    }

    std::error_code typeError;
    if (!fs::is_regular_file(file, typeError) || typeError) {
        return MakeError(ErrorKind::ConfigFailed, "the runtime config path is not a regular file");
    }

    std::string text;
    {
        std::ifstream input(file, std::ios::binary);
        if (!input) {
            return MakeError(ErrorKind::ConfigFailed, "could not read the runtime config");
        }
        std::ostringstream buffer;
        buffer << input.rdbuf();
        text = buffer.str();
    }
    if (text.empty()) {
        return MakeError(ErrorKind::ConfigFailed, "the runtime config is empty");
    }

    const bool generatedByUs = text.rfind(kMarkerPrefix, 0) == 0;
    if (generatedByUs && text != rendered) {
        const core::Result<void> written = WriteConfigFile(path, rendered);
        if (!written) {
            return written.error();
        }
        RuntimeConfigInfo info;
        info.host = definition.host;
        info.port = definition.port;
        info.mixedPort = definition.mixedPort;
        info.secret = definition.secret;
        info.generated = true;
        return info;
    }

    core::Result<RuntimeConfigInfo> parsed = ReadExisting(text);
    if (!parsed) {
        return parsed;
    }
    parsed.value().generated = false;
    return parsed;
}

