constexpr char kMarker[] = "# Generated by ClashYuka runtime configuration. Do not edit.";
constexpr char kMarkerPrefix[] = "# Generated by ClashYuka";

fs::path PathFromUtf8(const std::string& value) {
    return fs::path(std::u8string(value.begin(), value.end()));
}

std::string ToUtf8(const fs::path& path) {
    const auto value = path.u8string();
    return std::string(value.begin(), value.end());
}

bool IsValidPort(int port) {
    return port > 0 && port <= 65535;
}

bool ParseController(const std::string& value, std::string& host, int& port) {
    const std::size_t separator = value.rfind(':');
    if (separator == std::string::npos) {
        return false;
    }
    std::string parsedHost = value.substr(0, separator);
    const std::string parsedPort = value.substr(separator + 1);
    if (parsedHost.empty()) {
        parsedHost = "127.0.0.1";
    }
    if (parsedHost.size() >= 2 && parsedHost.front() == '[' && parsedHost.back() == ']') {
        parsedHost = parsedHost.substr(1, parsedHost.size() - 2);
    }
    if (parsedHost.empty() || parsedHost == "0.0.0.0" || parsedHost == "::") {
        return false;
    }
    try {
        const int parsed = std::stoi(parsedPort);
        if (!IsValidPort(parsed)) {
            return false;
        }
        host = std::move(parsedHost);
        port = parsed;
        return true;
    } catch (const std::exception&) {
        return false;
    }
}

core::Result<RuntimeConfigInfo> ReadExisting(const std::string& text) {
    YAML::Node root;
    try {
        root = YAML::Load(text);
    } catch (const YAML::Exception& error) {
        return MakeError(ErrorKind::ConfigFailed,
                         std::string("existing runtime config is not valid YAML: ") + error.what());
    }
    if (!root.IsMap()) {
        return MakeError(ErrorKind::ConfigFailed,
                         "existing runtime config is not a YAML mapping");
    }

    RuntimeConfigInfo info;
    const YAML::Node controller = root["external-controller"];
    if (!controller || !controller.IsScalar()) {
        return MakeError(
            ErrorKind::ConfigFailed,
            "existing runtime config has no external-controller; ClashYuka needs a local "
            "controller endpoint");
    }
    std::string controllerValue;
    try {
        controllerValue = controller.as<std::string>();
    } catch (const YAML::Exception&) {
        return MakeError(ErrorKind::ConfigFailed,
                         "existing runtime config has an invalid external-controller");
    }
    if (!ParseController(controllerValue, info.host, info.port)) {
        return MakeError(ErrorKind::ConfigFailed,
                         "existing runtime config has an invalid external-controller");
    }

    const YAML::Node secret = root["secret"];
    if (secret && secret.IsScalar()) {
        try {
            info.secret = secret.as<std::string>();
        } catch (const YAML::Exception&) {
            return MakeError(ErrorKind::ConfigFailed,
                             "existing runtime config has an invalid secret");
        }
    }

    const YAML::Node mixed = root["mixed-port"];
    if (mixed && mixed.IsScalar()) {
        try {
            const int port = mixed.as<int>();
            if (IsValidPort(port)) {
                info.mixedPort = port;
            }
        } catch (const YAML::Exception&) {
            // No usable mixed port was declared.
        }
    }

    info.generated = false;
    return info;
}

core::Result<void> WriteConfigFile(const std::string& path, const std::string& contents) {
    const fs::path file = PathFromUtf8(path);
    if (file.has_parent_path()) {
        std::error_code createError;
        fs::create_directories(file.parent_path(), createError);
        if (createError) {
            return MakeError(ErrorKind::ConfigFailed,
                             "could not create the runtime config directory: " +
                                 createError.message());
        }
    }

    fs::path temp = file;
    temp += ".tmp";
    {
        std::ofstream output(temp, std::ios::binary | std::ios::trunc);
        if (!output) {
            return MakeError(ErrorKind::ConfigFailed,
                             "could not open the runtime config for writing");
        }
        output << contents;
        output.flush();
        if (!output) {
            output.close();
            std::error_code ignored;
            fs::remove(temp, ignored);
            return MakeError(ErrorKind::ConfigFailed, "could not write the runtime config");
        }
    }

    std::string replaceError;
    if (!platform::ReplaceFileAtomically(ToUtf8(temp), ToUtf8(file), &replaceError)) {
        std::error_code ignored;
        fs::remove(temp, ignored);
        return MakeError(ErrorKind::ConfigFailed,
                         "could not replace the runtime config: " + replaceError);
    }

    std::error_code ignored;
    fs::permissions(file, fs::perms::owner_read | fs::perms::owner_write,
                    fs::perm_options::replace, ignored);
    return {};
}

